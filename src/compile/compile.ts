import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import type { Concept, Knowledge } from "../index/load.ts";
import { shortHash } from "../lib/inbox.ts";
import { isAlwaysOn } from "../schema/concept.ts";

export const BEGIN = "<!-- kb:begin -->";
export const END = "<!-- kb:end -->";

/** Where each compiled output goes and how big it may be. */
export const TARGETS = {
  claude: { file: "claude.md", lines: 150 },
  agents: { file: "agents.md", lines: 150 },
} as const;

export const PASTE_LIMITS: Record<string, number> = {
  chatgpt: 1500,
  claude: 3000,
  gemini: 3000,
  muse: 3000,
  instinct: 1000,
};

const TYPE_ORDER = [
  "instruction",
  "preference",
  "fact",
  "project",
  "person",
  "tool",
  "data_source",
];
const TYPE_HEADINGS: Record<string, string> = {
  instruction: "How to work with me",
  preference: "Preferences",
  fact: "Facts",
  project: "Projects",
  person: "People",
  tool: "Tools",
  data_source: "Where data lives",
};

/** One line per concept: the description if present, else the first paragraph of the body. */
export function summarize(c: Concept, max = 200): string {
  const clean = (s: string) =>
    s
      .replace(/\[\^[^\]]+\]/g, "")
      .replace(/\s+/g, " ")
      .trim();
  // The body is the fact itself; the description is a search summary. Use the body's first
  // paragraph when it fits, so the assistant gets the actual content, not a pointer to it.
  const para = clean(c.body.split(/\n\s*\n/)[0] ?? "");
  const prefix = `${c.meta.title}: `;
  const text =
    para && prefix.length + para.length <= max ? para : clean(c.meta.description ?? "") || para;
  const line = `${prefix}${text}`;
  return line.length > max ? `${line.slice(0, max - 1)}…` : line;
}

/** Always-on concepts, most important types first, then newest first. */
export function alwaysOn(k: Knowledge): Concept[] {
  return k.concepts
    .filter((c) => isAlwaysOn(c.meta))
    .sort(
      (a, b) =>
        TYPE_ORDER.indexOf(a.meta.type) - TYPE_ORDER.indexOf(b.meta.type) ||
        b.lastUpdated.localeCompare(a.lastUpdated),
    );
}

export type Compiled = {
  text: string;
  conceptIds: string[];
  omitted: string[];
};

/** Build a Markdown profile section that fits in `maxLines`. Lowest-priority concepts are dropped first. */
export function profileSection(
  k: Knowledge,
  maxLines: number,
  opts: { mcp?: boolean } = {},
): Compiled {
  const header = [
    "## About me (from my knowledge hub)",
    "",
    "Generated by kb-hub from my reviewed knowledge base. Do not edit between the kb markers; changes are overwritten.",
    opts.mcp === false
      ? ""
      : "For anything not listed here, search the knowledge hub MCP server (search_knowledge) before asking me, and use flag_knowledge when something is missing or wrong.",
    "",
  ];
  const skills = k.skills.length
    ? ["### Skills", "", ...k.skills.map((s) => `- ${s.name}: ${s.description.split("\n")[0]}`), ""]
    : [];
  const budget = maxLines - header.length - skills.length;
  const included: Concept[] = [];
  const omitted: string[] = [];
  let used = 0;
  let lastType = "";
  for (const c of alwaysOn(k)) {
    const cost = (c.meta.type !== lastType ? 3 : 0) + 1;
    if (used + cost > budget) {
      omitted.push(c.id);
      continue;
    }
    used += cost;
    lastType = c.meta.type;
    included.push(c);
  }
  const body: string[] = [];
  let current = "";
  for (const c of included) {
    if (c.meta.type !== current) {
      if (current) body.push("");
      body.push(`### ${TYPE_HEADINGS[c.meta.type] ?? c.meta.type}`, "");
      current = c.meta.type;
    }
    body.push(`- ${summarize(c)}`);
  }
  if (body.length) body.push("");
  const text = [...header, ...body, ...skills]
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd();
  return { text: `${text}\n`, conceptIds: included.map((c) => c.id), omitted };
}

/** Plain-text profile for apps that only take pasted text, within a character budget. */
export function pasteBlock(k: Knowledge, maxChars: number): Compiled {
  const head = "About me (keep this in mind in our conversations):\n";
  const lines: string[] = [];
  const ids: string[] = [];
  const omitted: string[] = [];
  let size = head.length;
  for (const c of alwaysOn(k)) {
    const line = `- ${summarize(c, 160)}\n`;
    if (size + line.length > maxChars) {
      omitted.push(c.id);
      continue;
    }
    size += line.length;
    lines.push(line);
    ids.push(c.id);
  }
  return { text: head + lines.join(""), conceptIds: ids, omitted };
}

/** Replace (or append) the marked kb section in a file's text, leaving everything else untouched. */
export function upsertMarkedSection(existing: string, section: string): string {
  const block = `${BEGIN}\n${section.trimEnd()}\n${END}`;
  const start = existing.indexOf(BEGIN);
  const end = existing.indexOf(END);
  if (start !== -1 && end > start) {
    return existing.slice(0, start) + block + existing.slice(end + END.length);
  }
  const sep = existing.trim() ? (existing.endsWith("\n") ? "\n" : "\n\n") : "";
  return `${existing}${sep}${block}\n`;
}

export type Manifest = {
  generated_at: string;
  outputs: Record<string, { file: string; hash: string; concepts: string[]; omitted: string[] }>;
  concept_hashes: Record<string, string>;
};

/** Hash of what a tool would see for one concept, used to count "changes behind". */
export function conceptHash(c: Concept): string {
  return shortHash(`${summarize(c)}|${c.meta.status}|${c.meta.sensitivity}`);
}

/** Write every compiled output to <knowledge>/build/ plus a manifest. */
export async function compileAll(root: string, k: Knowledge, now = new Date()): Promise<Manifest> {
  const outputs: Manifest["outputs"] = {};
  const write = async (name: string, file: string, c: Compiled) => {
    const full = join(root, "build", file);
    await mkdir(dirname(full), { recursive: true });
    await writeFile(full, c.text);
    outputs[name] = {
      file: `build/${file}`,
      hash: shortHash(c.text),
      concepts: c.conceptIds,
      omitted: c.omitted,
    };
  };
  await write("claude", TARGETS.claude.file, profileSection(k, TARGETS.claude.lines));
  await write("agents", TARGETS.agents.file, profileSection(k, TARGETS.agents.lines));
  for (const [tool, limit] of Object.entries(PASTE_LIMITS)) {
    await write(`paste:${tool}`, `paste/${tool}.md`, pasteBlock(k, limit));
  }
  const concept_hashes = Object.fromEntries(alwaysOn(k).map((c) => [c.id, conceptHash(c)]));
  const manifest: Manifest = { generated_at: now.toISOString(), outputs, concept_hashes };
  await writeFile(join(root, "build", "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}
